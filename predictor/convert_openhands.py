"""Convert OpenHands trajectories (Nebius, CoderForge) into the shared step format.

    python predictor/convert_openhands.py nebius
    python predictor/convert_openhands.py coderforge      # all three splits, 6 files at a time

Both datasets were generated by one model (Qwen3-Coder-480B) with OpenHands tools. To keep
the features scaffold-agnostic, every tool call is rewritten as the shell command that
would have the same effect, and placed in a ```bash block like mini-swe-agent actions:

    execute_bash {command: c}                  -> c
    str_replace_editor view {path: p}          -> cat p
    str_replace_editor create {path, text}     -> cat > p <<'EOF' ... EOF
    str_replace_editor str_replace/insert/undo -> str_replace p
    finish                                     -> echo COMPLETE_TASK_AND_SUBMIT_FINAL_OUTPUT
    think, task_tracker                        -> (no command)

OpenHands reports "[Command finished with exit code N]"; it becomes <returncode>N</returncode>.
Neither dataset logs token usage, so tokens are estimated as characters / 4, the same
fallback coverage/download_swebench.py uses for older submissions. Observations are cut to
their first and last 3,000 characters to keep the files small.

A task can have several runs, so task_id is "<instance_id>@<run>"; step_features.py strips the
suffix to look up the gold patch. Tasks from the 12 SWE-bench Verified repositories are
dropped, so these runs can be used to train a predictor that is tested on Verified (Nebius
by exact repository name, none dropped; CoderForge by verified_repo_pattern, which also
drops repositories whose names start with a Verified one).

CoderForge is converted one parquet file per shard, in parallel and resumable; the agent
is "coderforge_<split>" and the run number comes from the trajectory id. Gold patches come
from nebius/SWE-rebench (SWE-rebench tasks) and SWE-bench/SWE-smith (SWE-smith tasks); the
R2E-Gym tasks have none, so their gold features are missing.

Output: data/openhands/nebius.jsonl.gz, data/openhands/coderforge/<file>.jsonl.gz, and
data/meta/{swerebench,swesmith}_gold.parquet
"""

from __future__ import annotations

import argparse
import gzip
import json
import re
import time
from multiprocessing import Pool
from pathlib import Path

import pandas as pd
import pyarrow.parquet as pq
from huggingface_hub import HfFileSystem

NEBIUS = "datasets/nebius/SWE-rebench-openhands-trajectories/trajectories.parquet"
CODERFORGE = "datasets/togethercomputer/CoderForge-Preview/trajectories"
GOLD_SOURCE = "datasets/nebius/SWE-rebench"  # gold patches and tests for SWE-rebench tasks
EXIT_CODE = re.compile(r"exit code (-?\d+)")
KEEP = 3000


def _args(call: dict) -> tuple[str, dict]:
    fn = call.get("function") or {}
    args = fn.get("arguments") or {}
    if isinstance(args, str):
        try:
            args = json.loads(args)
        except json.JSONDecodeError:
            args = {"command": args}
    return fn.get("name") or "", args if isinstance(args, dict) else {}


def shell_command(name: str, args: dict) -> str:
    path = args.get("path", "")
    if name == "execute_bash":
        return str(args.get("command", ""))
    if name == "str_replace_editor":
        sub = args.get("command", "")
        if sub == "view":
            return f"cat {path}"
        if sub == "create":
            return f"cat > {path} <<'EOF'\n{str(args.get('file_text', ''))[:KEEP]}\nEOF"
        return f"str_replace {path}"
    if name == "finish":
        return "echo COMPLETE_TASK_AND_SUBMIT_FINAL_OUTPUT"
    return ""


def clip(text: str) -> str:
    return text if len(text) <= 2 * KEEP else text[:KEEP] + "\n[...]\n" + text[-KEEP:]


def to_steps(messages: list[dict]) -> list[dict]:
    steps, chars = [], 0
    for msg in messages:
        role, content = msg.get("role"), msg.get("content") or ""
        if not isinstance(content, str):
            content = json.dumps(content)
        if role == "assistant":
            calls = [_args(c) for c in (msg.get("tool_calls") or [])]
            cmds = [c for c in (shell_command(n, a) for n, a in calls) if c]
            raw = content + "".join(json.dumps(a) for _, a in calls)
            action = content + ("\n```bash\n" + "\n".join(cmds) + "\n```" if cmds else "")
            steps.append({"tokens_in": chars // 4, "tokens_out": len(raw) // 4,
                          "action": action, "observation": ""})
            chars += len(raw)
        else:
            chars += len(content)
            if role == "tool" and steps:
                m = EXIT_CODE.findall(content)
                obs = (f"<returncode>{m[-1]}</returncode>\n" if m else "") + clip(content)
                sep = "\n" if steps[-1]["observation"] else ""
                steps[-1]["observation"] += sep + obs
    return steps


def verified_repos() -> set[str]:
    meta = pd.read_parquet("data/meta/swebench_verified.parquet")
    return {r.split("/")[1].lower() for r in meta["repo"]}


def repo_of(instance_id: str) -> str:
    """'owner__repo-123' -> 'repo'"""
    return instance_id.split("__", 1)[-1].rsplit("-", 1)[0].lower()


def write_runs(rows, out: Path, agent: str, max_runs: int | None) -> dict:
    skip = verified_repos()
    runs_per_task: dict[str, int] = {}
    stats = {"runs": 0, "steps": 0, "resolved": 0, "skipped_verified_repo": 0}
    tmp = out.with_suffix(".tmp")
    with gzip.open(tmp, "wt") as f:
        for instance_id, messages, outcome in rows:
            if repo_of(instance_id) in skip:
                stats["skipped_verified_repo"] += 1
                continue
            steps = to_steps(messages)
            if not steps:
                continue
            n = runs_per_task.get(instance_id, 0)
            runs_per_task[instance_id] = n + 1
            for i, step in enumerate(steps, start=1):
                f.write(json.dumps({"task_id": f"{instance_id}@{n}", "agent": agent, "step": i,
                                    **step, "outcome": int(outcome)}) + "\n")
            stats["runs"] += 1
            stats["steps"] += len(steps)
            stats["resolved"] += int(outcome)
            if stats["runs"] % 5000 == 0:
                print(stats, flush=True)
            if max_runs and stats["runs"] >= max_runs:
                break
    tmp.rename(out)
    return stats


def nebius_rows(fs: HfFileSystem):
    with fs.open(NEBIUS) as fh:
        pf = pq.ParquetFile(fh)
        for i in range(pf.num_row_groups):
            t = pf.read_row_group(i, columns=["instance_id", "trajectory", "resolved"]).to_pylist()
            for r in t:
                yield r["instance_id"], r["trajectory"], r["resolved"]


def verified_repo_pattern() -> re.Pattern:
    """Matches a task id from any SWE-bench Verified repository, conservatively: a task from a
    repository whose name starts with a Verified one (pytest-xdist, flask-login) is matched too."""
    meta = pd.read_parquet("data/meta/swebench_verified.parquet")
    names = sorted({r.split("/")[1].lower() for r in meta["repo"]})
    alternatives = "|".join(re.escape(n).replace(r"\-", "[-_]") for n in names)
    return re.compile(rf"(?:^|__|_)(?:{alternatives})(?:[_.\-]|$)", re.IGNORECASE)


def convert_coderforge_file(job: tuple[str, Path]) -> dict:
    """Convert one CoderForge parquet file into one shard. Skips shards already written."""
    path, out_dir = job
    name = path.split("/")[-1].removesuffix(".parquet")
    out = out_dir / f"{name}.jsonl.gz"
    if out.exists():
        return {"file": name, "existing": 1}
    split = name.split("-")[0]
    pattern = verified_repo_pattern()
    fs = HfFileSystem()
    for attempt in range(4):
        try:
            with fs.open(path) as fh:
                table = pq.read_table(fh, columns=["trajectory_id", "messages", "reward"]).to_pylist()
            break
        except Exception:
            if attempt == 3:
                raise
            time.sleep(5 * 2**attempt)
    stats = {"file": name, "runs": 0, "steps": 0, "resolved": 0, "errored": 0,
             "skipped_verified_repo": 0}
    tmp = out.with_name(out.name + ".tmp")
    with gzip.open(tmp, "wt") as f:
        for r in table:
            if r["reward"] not in (0.0, 1.0):
                stats["errored"] += 1  # -1 marks a run that errored
                continue
            m = re.match(r"^(.*)_run(\d+)$", r["trajectory_id"])
            instance, run = (m.group(1), m.group(2)) if m else (r["trajectory_id"], "0")
            if pattern.search(instance):
                stats["skipped_verified_repo"] += 1
                continue
            steps = to_steps(json.loads(r["messages"]))
            if not steps:
                continue
            for i, step in enumerate(steps, start=1):
                f.write(json.dumps({"task_id": f"{instance}@{run}", "agent": f"coderforge_{split}",
                                    "step": i, **step, "outcome": int(r["reward"])}) + "\n")
            stats["runs"] += 1
            stats["steps"] += len(steps)
            stats["resolved"] += int(r["reward"])
    tmp.rename(out)
    return stats


def convert_coderforge(fs: HfFileSystem, splits: list[str], workers: int) -> dict:
    out_dir = Path("data/openhands/coderforge")
    out_dir.mkdir(parents=True, exist_ok=True)
    files = sorted(p for p in fs.ls(CODERFORGE, detail=False)
                   if p.endswith(".parquet") and p.split("/")[-1].split("-")[0] in splits)
    total: dict = {}
    with Pool(workers) as pool:
        for i, stats in enumerate(pool.imap_unordered(convert_coderforge_file,
                                                      [(p, out_dir) for p in files]), start=1):
            for key, value in stats.items():
                if key != "file":
                    total[key] = total.get(key, 0) + value
            if i % 25 == 0 or i == len(files):
                print(f"{i}/{len(files)} files: {total}", flush=True)
    return total


def fetch_swesmith_gold(fs: HfFileSystem, out: Path) -> None:
    """Gold files and FAIL_TO_PASS for SWE-smith tasks, ids written the way CoderForge writes them.

    SWE-smith's patch is the one that introduced the bug; it touches the same files as the fix.
    """
    frames = []
    for p in fs.glob("datasets/SWE-bench/SWE-smith/**/*.parquet"):
        with fs.open(p) as fh:
            t = pq.read_table(fh, columns=["instance_id", "repo", "patch", "FAIL_TO_PASS"]).to_pylist()
        frames.append(pd.DataFrame(t))
    gold = pd.concat(frames, ignore_index=True)
    gold["instance_id"] = gold["instance_id"].str.replace(".", "_", regex=False)
    gold["FAIL_TO_PASS"] = gold["FAIL_TO_PASS"].map(lambda v: json.dumps(list(v) if v is not None else []))
    gold["test_patch"] = ""
    gold = gold.drop_duplicates("instance_id")
    gold.to_parquet(out)
    print(f"wrote {out}: {len(gold)} tasks")


def fetch_gold(fs: HfFileSystem, out: Path) -> None:
    """Gold patch, test patch and FAIL_TO_PASS for SWE-rebench tasks, same columns as Verified."""
    files = [p for p in fs.glob(f"{GOLD_SOURCE}/**/*.parquet")]
    cols = ["instance_id", "repo", "patch", "test_patch", "FAIL_TO_PASS", "PASS_TO_PASS", "created_at"]
    frames = []
    for p in files:
        with fs.open(p) as fh:
            have = set(pq.ParquetFile(fh).schema.names)
            fh.seek(0)
            frames.append(pq.read_table(fh, columns=[c for c in cols if c in have]).to_pandas())
    gold = pd.concat(frames, ignore_index=True).drop_duplicates("instance_id")
    gold.to_parquet(out)
    print(f"wrote {out}: {len(gold)} tasks")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("source", choices=["nebius", "coderforge"])
    parser.add_argument("--max-runs", type=int, help="nebius only")
    parser.add_argument("--splits", default="SWE_Rebench,SWE_Smith,R2E_Gym",
                        help="CoderForge splits, comma-separated")
    parser.add_argument("--workers", type=int, default=6, help="coderforge only")
    args = parser.parse_args()

    fs = HfFileSystem()
    Path("data/openhands").mkdir(parents=True, exist_ok=True)
    gold_path = Path("data/meta/swerebench_gold.parquet")
    if not gold_path.exists():
        fetch_gold(fs, gold_path)
    if args.source == "nebius":
        stats = write_runs(nebius_rows(fs), Path("data/openhands/nebius.jsonl.gz"),
                           "nebius_openhands_qwen3-coder-480b", args.max_runs)
    else:
        smith_path = Path("data/meta/swesmith_gold.parquet")
        if not smith_path.exists():
            fetch_swesmith_gold(fs, smith_path)
        stats = convert_coderforge(fs, args.splits.split(","), args.workers)
    print(f"done {args.source}: {stats}")


if __name__ == "__main__":
    main()
